DATE_PAT = ["{}", "今天{}", "昨天{}", "刚才{}", "昨晚{}", "前天{}",
            "{d}号{}", "{m}月{d}号{}", "今天花了{}", "昨天花了{}", "早上{}", "晚上{}"]

synthetic, seen = [], set()
for cat, verbs in V.items():
    for v in verbs:
        for _ in range(12):
            pat = random.choice(DATE_PAT)
            text = pat.format(v, d=random.randint(1, 28), m=random.randint(1, 10))
            if random.random() < 0.7:
                text += AMT()
            text = text.strip()
            if not any(ch.isdigit() for ch in text):   # 与管线约定一致：无金额句子跳过
                text += AMT()
            if text in val_texts or text in seen:
                continue
            seen.add(text)
            synthetic.append({"text": text, "label": cat})

train = data["train"] + synthetic
random.shuffle(train)
json.dump({"labels": data["labels"], "train": train, "val": data["val"]},
          open("/workspace/zhang_api/cls_dataset_aug.json", "w", encoding="utf-8"),
          ensure_ascii=False, indent=1)
print(f"合成样本 {len(synthetic)} 条 | 增广后训练集 {len(train)} 条 | 验证集不变 {len(data['val'])} 条")
assert not ({s["text"] for s in train} & val_texts), "验证集泄漏！"
